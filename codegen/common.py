"""Helpers shared by the language emitters."""

from __future__ import annotations

import re

from ir import API, Schema

HEADER = "Code generated by codegen/gen.py from spec/{file}. DO NOT EDIT."


def words(s: str) -> list[str]:
    """Splits snake_case, kebab-case, dotted and camelCase names into words."""
    out = []
    for part in re.split(r"[^A-Za-z0-9]+", s):
        out += re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+", part) if part else []
    return out


def snake(s: str) -> str:
    return "_".join(w.lower() for w in words(s))


def pascal(s: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in words(s))


def _same(a: Schema, b: Schema) -> bool:
    key = lambda s: [(f.name, repr(f.type), f.required) for f in s.fields]
    return key(a) == key(b)


def shared_schemas(v1: API, partner: API) -> set[str]:
    """Schema names both specs define with identical shapes. Emitters define
    them once (in the v1 module) and the partner module reuses them."""
    both = set(v1.schemas) & set(partner.schemas)
    differ = [n for n in both if not _same(v1.schemas[n], partner.schemas[n])]
    if differ:
        raise ValueError(f"schemas differ between specs: {differ}")
    return both


def paragraphs(*docs: str) -> list[str]:
    """Doc text as lines, with blank lines between non-empty parts."""
    lines: list[str] = []
    for d in docs:
        d = (d or "").strip()
        if not d:
            continue
        if lines:
            lines.append("")
        lines += d.splitlines()
    return lines
